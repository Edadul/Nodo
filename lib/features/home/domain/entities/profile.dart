class Profile {
  final String name;
  final String username;
  final String bio;
  final String avatar;
  final int posts;
  final int followers;
  final int favorites;

  const Profile({
    required this.name,
    required this.username,
    required this.bio,
    required this.avatar,
    required this.posts,
    required this.followers,
    required this.favorites,
  });
}
